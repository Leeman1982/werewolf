#!/usr/bin/env python3
"""
ttf_to_xbm.py — render fixed strings from a TTF into XBM bitmaps for U8g2.

Two modes:

  Single word, auto-sized to fit a box (the original splash-logo use):
    python3 tools/ttf_to_xbm.py --ttf minotaur.ttf --text "StageFright" \
        --out splash_logo.h --name SPLASH_LOGO --maxw 126 --maxh 30

  A fixed size, one or more strings, batched into one header (menu labels,
  a two-line splash title -- anywhere the string set is known at build time,
  so there's no need for a full glyph-by-glyph font):
    python3 tools/ttf_to_xbm.py --ttf minotaur.ttf --size 14 --out menu.h \
        --strings "STEP EDIT=MINO_STEP_EDIT" "PATTERN=MINO_PATTERN"

Each `--strings` entry is `TEXT=NAME`, `TEXT=NAME@SIZE` or
`TEXT=NAME@SIZE+TRACK`; NAME becomes `NAME_W`/`NAME_H`/`NAME_BITS`, and the
optional `@SIZE`/`+TRACK` override `--size`/`--track` for that one string.
Those per-string overrides are what let a whole splash -- a big title line, a
smaller second line and a credit line that needs its own tracking -- come out
of ONE run into ONE header, instead of several runs that then have to be
pasted together by hand.  Drawn with u8g2.drawXBM(x, y, W, H, BITS).
"""
import argparse
import shlex
import sys
from PIL import Image, ImageFont, ImageDraw

ap = argparse.ArgumentParser()
ap.add_argument('--ttf', required=True)
ap.add_argument('--out', required=True)
ap.add_argument('--threshold', type=int, default=110)
# Auto-sized single-word mode
ap.add_argument('--text')
ap.add_argument('--name', default='SPLASH_LOGO')
ap.add_argument('--maxw', type=int, default=126)
ap.add_argument('--maxh', type=int, default=30)
# Fixed-size batch mode
ap.add_argument('--size', type=int)
ap.add_argument('--strings', nargs='*', default=[])
# Extra pixels inserted between glyphs.  A display face like Minotaur is drawn
# with almost no sidebearing, which is fine in print but merges adjacent
# strokes once the whole word is only a dozen pixels tall on a 1-bit panel
# (its B and I run into one solid block).  Tracking buys those strokes a gap
# back.  Applies to batch mode only; 0 keeps the font's own metrics exactly.
ap.add_argument('--track', type=int, default=0)
a = ap.parse_args()


def rasterize(text, size, track=0):
    fnt = ImageFont.truetype(a.ttf, size)
    canvas = Image.new('L', (4000, 400), 0)
    d = ImageDraw.Draw(canvas)
    if track:
        # Draw glyph by glyph so `track` can be added to each advance.  Note
        # this drops kerning; at these sizes the face has none worth keeping,
        # and the point of the exercise is more space between glyphs anyway.
        x = 50.0
        for ch in text:
            d.text((x, 50), ch, font=fnt, fill=255)
            x += fnt.getlength(ch) + track
    else:
        d.text((50, 50), text, font=fnt, fill=255)
    bb = canvas.getbbox()
    return canvas.crop(bb)


def to_xbm_bytes(img):
    w, h = img.size
    stride = (w + 7) // 8
    data = bytearray(stride * h)
    px = img.load()
    on = 0
    for y in range(h):
        for x in range(w):
            if px[x, y] >= a.threshold:
                data[y * stride + (x >> 3)] |= (1 << (x & 7))
                on += 1
    return data, on


def emit_array(fh, name, img, comment, size=None):
    data, on = to_xbm_bytes(img)
    w, h = img.size
    fh.write('// %s\n' % comment)
    fh.write('#define %s_W %d\n#define %s_H %d\n\n' % (name, w, name, h))
    fh.write('static const uint8_t %s_BITS[] = {\n' % name)
    for i in range(0, len(data), 12):
        fh.write('  ' + ','.join('0x%02X' % b for b in data[i:i + 12]) + ',\n')
    fh.write('};\n\n')
    print('%-24s %dx%d  %s  %d px set' % (name, w, h,
          'size=%d' % size if size is not None else 'size=(auto)', on))


with open(a.out, 'w') as fh:
    fh.write('#pragma once\n#include <Arduino.h>\n\n')
    fh.write('// GENERATED by tools/ttf_to_xbm.py from %s - do not edit.\n' % a.ttf.split('/')[-1])
    fh.write('// Drawn with u8g2.drawXBM(x, y, W, H, BITS).\n')
    fh.write('//\n// Regenerate with:\n//   %s\n\n'
             % ' '.join(shlex.quote(x) for x in ['python3'] + sys.argv))

    if a.text is not None:
        size = None
        for s in range(64, 6, -1):
            img = rasterize(a.text, s)
            if img.width <= a.maxw and img.height <= a.maxh:
                size = s
                break
        if size is None:
            raise SystemExit('nothing fits')
        img = rasterize(a.text, size)
        fh.write('//   text : "%s"\n//   size : %d px -> %dx%d\n\n' % (a.text, size, img.width, img.height))
        emit_array(fh, a.name, img, 'text="%s" size=%dpx' % (a.text, size), size)

    if a.strings:
        for spec in a.strings:
            text, name = spec.split('=', 1)
            size, track = a.size, a.track
            if '@' in name:
                name, sz = name.rsplit('@', 1)
                if '+' in sz:
                    sz, tr = sz.split('+', 1)
                    track = int(tr)
                size = int(sz)
            if size is None:
                raise SystemExit('%r has no @SIZE and --size was not given' % spec)
            img = rasterize(text, size, track)
            emit_array(fh, name, img, 'text="%s" size=%dpx track=%dpx'
                       % (text, size, track), size)

print('wrote', a.out)
